/* ---- SysTick Timer Initialization ----
 * Configures the Cortex-M4 SysTick to provide a 1ms timebase for HAL.
 * SystemCoreClock = 168MHz, reload value = 168MHz/1000 = 168000.
 * This is the heartbeat for HAL_Delay() and all HAL timeout functions.
 */

/**
  * @brief  Initialize SysTick timer for 1ms periodic interrupt.
  *         Called by HAL_Init() during system startup.
  * @param  TickPriority: interrupt priority for SysTick
  * @retval HAL_OK on success, HAL_ERROR if reload value > 24-bit or priority invalid
  */
HAL_StatusTypeDef HAL_InitTick(uint32_t TickPriority)
{
  /* SysTick reload = SystemCoreClock / 1000 — fires every 1ms */
  if (HAL_SYSTICK_Config(SystemCoreClock / 1000) > 0U)
  {
    return HAL_ERROR;                        /* reload value exceeds 24-bit register limit */
  }

  /* Validate and set SysTick interrupt priority */
  if (TickPriority < (1UL << __NVIC_PRIO_BITS))
  {
    HAL_NVIC_SetPriority(SysTick_IRQn, TickPriority, 0U);
    uwTickPrio = TickPriority;
  }
  else
  {
    return HAL_ERROR;                        /* priority value out of valid range */
  }

  return HAL_OK;
}

